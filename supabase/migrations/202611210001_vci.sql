create function public.vci_read(route text,params jsonb default '{}') returns jsonb
language plpgsql stable security invoker set search_path='' as $$
declare a public.vci_accounts:=vci_private.account(); result jsonb; total bigint; off_n integer; q text; f text;
begin
 if route='/me' then
  select jsonb_build_object('user',to_jsonb(a)-'auth_id'-'credentials_since'-'import_id'-'import_index'||jsonb_build_object('class_code',coalesce(c.code,''),'campus',coalesce(c.campus,''),'class_year',c.year),'csrf','') into result from (select 1) x left join public.vci_classes c on c.id=a.class_id;
 elsif route='/classes' then
  select coalesce(jsonb_agg(to_jsonb(c)||jsonb_build_object('student_count',(select count(*) from public.vci_accounts u where u.class_id=c.id and u.role='student')) order by c.campus,c.code),'[]') into result from public.vci_classes c;
 elsif route='/students' then
  if a.role<>'admin' then raise exception 'Chỉ quản trị được xem danh sách sinh viên' using errcode='42501'; end if;
  off_n:=greatest(0,least(coalesce((params->>'offset')::int,0),1000000)); q:=public.vci_normalize(trim(coalesce(params->>'search',''))); f:=coalesce(params->>'field','all');
  with matching as (
   select u.id,u.username,u.full_name,u.class_id,d.national_id,c.code class_code,c.campus,c.year class_year
   from public.vci_accounts u join public.vci_classes c on c.id=u.class_id join public.vci_student_details d on d.account_id=u.id
   where u.role='student' and (coalesce(params->>'class_id','')='' or c.id=(params->>'class_id')::bigint)
   and (coalesce(params->>'year','')='' or case when params->>'year'='unassigned' then c.year is null else c.year=(params->>'year')::int end)
   and not exists(select 1 from regexp_split_to_table(q,'\s+') token where token<>'' and position(token in public.vci_normalize(case f when 'name' then u.full_name when 'national_id' then d.national_id when 'class' then c.code else concat_ws(' ',u.full_name,u.username,d.national_id,c.code,c.campus,c.year) end))=0)
  ) select jsonb_build_object('total',(select count(*) from matching),'offset',off_n,'rows',coalesce((select jsonb_agg(to_jsonb(x)) from(select * from matching order by username,id limit 100 offset off_n)x),'[]')) into result;
 elsif route ~ '^/students/[0-9]+$' then
  if a.role<>'admin' then raise exception 'Chỉ quản trị được xem hồ sơ' using errcode='42501'; end if;
  select to_jsonb(u)-'auth_id'-'credentials_since'-'import_id'-'import_index'||to_jsonb(d)-'account_id'||jsonb_build_object('class_code',c.code,'campus',c.campus,'class_year',c.year) into result
  from public.vci_accounts u join public.vci_student_details d on d.account_id=u.id join public.vci_classes c on c.id=u.class_id where u.id=split_part(route,'/',3)::bigint;
 elsif route='/timetable-links' then
  select coalesce(jsonb_agg(to_jsonb(x) order by x.academic_year desc,x.updated_at desc),'[]') into result from(select t.*,c.code class_code,c.campus,c.year class_year from public.vci_timetable_links t join public.vci_classes c on c.id=t.class_id where coalesce(params->>'class_id','')='' or t.class_id=(params->>'class_id')::bigint)x;
 elsif route='/schedules' then
  if (params->>'end')::date<(params->>'start')::date or (params->>'end')::date-(params->>'start')::date>370 then raise exception 'Khoảng ngày không hợp lệ'; end if;
  select coalesce(jsonb_agg(to_jsonb(x) order by x.date,x.start),'[]') into result from(select s.id,s.class_id,s.date,to_char(s.start,'HH24:MI') start,to_char(s."end",'HH24:MI') "end",s.subject,s.lecturer,s.room,s.kind,s.status,s.note,s.updated_at,c.code class_code,c.campus from public.vci_schedules s join public.vci_classes c on c.id=s.class_id where date between (params->>'start')::date and (params->>'end')::date and (coalesce(params->>'class_id','')='' or s.class_id=(params->>'class_id')::bigint))x;
 elsif route='/notices' then
  select coalesce(jsonb_agg(to_jsonb(x) order by x.created_at desc),'[]') into result from(select n.*,coalesce(c.code,'Toàn trường') class_code,coalesce(c.campus,'') campus from public.vci_notices n left join public.vci_classes c on c.id=n.class_id order by n.created_at desc,n.id desc limit 200)x;
 elsif route='/audit' then
  if a.role<>'admin' then raise exception 'Chỉ quản trị được xem lịch sử' using errcode='42501'; end if;
  select coalesce(jsonb_agg(to_jsonb(x) order by x.id desc),'[]') into result from(select * from public.vci_audit order by id desc limit 200)x;
 else raise exception 'Không tìm thấy chức năng';
 end if;
 if result is null then raise exception 'Không tìm thấy dữ liệu' using errcode='P0002'; end if;
 return result;
end $$;
-- vci_read is invoker, so its guard needs schema/function access; tables stay
-- protected by RLS and the guard exposes only the caller's own account.
grant usage on schema vci_private to authenticated;
grant execute on function vci_private.account() to authenticated;
revoke all on function vci_private.provision_account(),vci_private.log(text,text,text) from public,anon,authenticated;

create function vci_private.impact(cid bigint) returns jsonb
language sql stable security definer set search_path='' as $$
 with snapshot as(select to_jsonb(c) c,
 (select coalesce(jsonb_agg(to_jsonb(u) order by u.id),'[]') from public.vci_accounts u where u.class_id=cid) students,
 (select coalesce(jsonb_agg(to_jsonb(s) order by s.id),'[]') from public.vci_schedules s where s.class_id=cid) schedules,
 (select coalesce(jsonb_agg(to_jsonb(n) order by n.id),'[]') from public.vci_notices n where n.class_id=cid) notices,
 (select coalesce(jsonb_agg(to_jsonb(t) order by t.id),'[]') from public.vci_timetable_links t where t.class_id=cid) timetable_links
 from public.vci_classes c where c.id=cid)
 select jsonb_build_object('class',c,'counts',jsonb_build_object('students',jsonb_array_length(students),'schedules',jsonb_array_length(schedules),'notices',jsonb_array_length(notices),'timetable_links',jsonb_array_length(timetable_links)),'revision',md5(row(c,students,schedules,notices,timetable_links)::text)) from snapshot
$$;
revoke all on function vci_private.impact(bigint) from public,anon,authenticated;

create function public.vci_write(method text,route text,body jsonb default '{}') returns jsonb
language plpgsql security definer set search_path='' as $$
declare a public.vci_accounts:=vci_private.account(); cid bigint; rid bigint; before_link public.vci_timetable_links; impact jsonb; r jsonb; result jsonb; errors jsonb:='[]'; rows_n jsonb:='[]'; seen text[]:='{}'; identities_seen text[]:='{}'; identity text; un text; cname text; cp text; batch uuid; ix integer:=0; rec record; valid boolean;
begin
 if a.role<>'admin' then raise exception 'Chỉ cán bộ quản trị được thực hiện chức năng này' using errcode='42501'; end if;
 perform pg_advisory_xact_lock(846311);
 if route='/classes' and method='POST' then
  insert into public.vci_classes(code,campus,year) values(trim(body->>'code'),trim(body->>'campus'),(body->>'year')::int) returning id into rid;
  perform vci_private.log(a.username,'create_class',body->>'code'); return jsonb_build_object('id',rid);
 elsif route ~ '^/classes/[0-9]+(/impact)?$' then
  cid:=split_part(route,'/',3)::bigint; select code,campus into cname,cp from public.vci_classes where id=cid for update;
  if cname is null then raise exception 'Lớp không tồn tại' using errcode='P0002'; end if;
  if method='GET' and route like '%/impact' then return vci_private.impact(cid);
  elsif method='PUT' then
   -- Renaming a class invalidates any unconfirmed spreadsheet selecting it.
   update public.vci_student_imports set expires_at=now() where not finished and exists(select 1 from jsonb_array_elements(rows) x where (x->>'class_id')::bigint=cid);
   update public.vci_schedule_imports set expires_at=now() where not published and exists(select 1 from jsonb_array_elements(rows) x where x->>'class_code'=cname and x->>'campus'=cp);
   if (body->>'campus')<>cp and exists(select 1 from public.vci_schedules where class_id=cid and status<>'nghi') then raise exception 'Lớp có lịch từng buổi. Hãy xử lý lịch trước khi đổi cơ sở.'; end if;
   update public.vci_classes set code=trim(body->>'code'),campus=trim(body->>'campus'),year=(body->>'year')::int where id=cid;
   perform vci_private.log(a.username,'update_class',cname||' → '||(body->>'code')); return '{"ok":true}';
  elsif method='DELETE' then
   impact:=vci_private.impact(cid);
   if body->>'confirmation_code' is distinct from cname or body->>'revision' is distinct from impact->>'revision' then raise exception 'Tên xác nhận không khớp hoặc dữ liệu đã thay đổi. Mở lại hộp xóa lớp.' using errcode='40001'; end if;
   if (impact#>>'{counts,students}')::int>0 and not coalesce((body->>'delete_students')::boolean,false) then raise exception 'Chưa xác nhận xóa tài khoản'; end if;
   if ((impact#>>'{counts,schedules}')::int+(impact#>>'{counts,notices}')::int+(impact#>>'{counts,timetable_links}')::int)>0 and not coalesce((body->>'delete_related')::boolean,false) then raise exception 'Chưa xác nhận xóa dữ liệu liên quan'; end if;
   update public.vci_student_imports set expires_at=now() where exists(select 1 from jsonb_array_elements(rows) x where (x->>'class_id')::bigint=cid);
   update public.vci_schedule_imports set expires_at=now() where exists(select 1 from jsonb_array_elements(rows) x where x->>'class_code'=cname and x->>'campus'=cp);
   delete from auth.users where id in(select auth_id from public.vci_accounts where class_id=cid and role='student');
   delete from public.vci_classes where id=cid;
   perform vci_private.log(a.username,'delete_class',cname||' / '||cp); return '{"ok":true}';
  end if;
 elsif route='/timetable-links' and method='POST' or route ~ '^/timetable-links/[0-9]+$' and method='PUT' then
  cid:=(body->>'class_id')::bigint;
  if method='PUT' then
   rid:=split_part(route,'/',3)::bigint; select * into before_link from public.vci_timetable_links where id=rid for update;
   if before_link.id is null then raise exception 'Không tìm thấy link lịch'; end if;
   if (body->>'version')::int is distinct from before_link.version then raise exception 'Link đã thay đổi. Làm mới rồi sửa lại.' using errcode='40001'; end if;
   if before_link.class_id<>cid then raise exception 'Không chuyển link sang lớp khác'; end if;
   update public.vci_timetable_links set academic_year=body->>'academic_year',semester=body->>'semester',kind=body->>'kind',title=trim(body->>'title'),url=trim(body->>'url'),note=coalesce(body->>'note',''),active=(body->>'active')::boolean,version=version+1,updated_at=now() where id=rid;
