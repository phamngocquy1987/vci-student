-- Run once in a NEW Supabase project. No demo users or student data are included.
begin;
create schema if not exists vci_private;
revoke all on schema vci_private from public, anon, authenticated;

create table public.vci_classes (
 id bigint generated by default as identity primary key,
 code text not null check(length(trim(code)) between 1 and 80),
 campus text not null check(campus in ('Hà Nội','Hồ Chí Minh','TP. Hồ Chí Minh','Đắk Lắk','Thái Nguyên','Cần Thơ','Bắc Ninh')),
 year integer check(year between 1900 and 2200), unique(code,campus)
);
create table public.vci_student_imports (
 id uuid primary key default gen_random_uuid(), owner_id uuid not null references auth.users(id) on delete cascade,
 rows jsonb not null, errors jsonb not null default '[]',
 created_at timestamptz not null default now(), expires_at timestamptz not null default now()+interval '24 hours',
 finished boolean not null default false
);
create table public.vci_accounts (
 id bigint generated by default as identity primary key,
 auth_id uuid not null unique references auth.users(id) on delete cascade,
 username text not null check(username ~ '^[A-Za-z0-9_.-]{1,100}$'),
 full_name text not null check(length(trim(full_name)) between 1 and 150),
 role text not null check(role in ('admin','student')),
 class_id bigint references public.vci_classes(id),
 import_id uuid references public.vci_student_imports(id) on delete set null,
 import_index integer, credentials_since timestamptz,
 check((role='admin' and class_id is null) or (role='student' and class_id is not null)),
 unique(import_id,import_index)
);
create table public.vci_schedule_imports (
 id uuid primary key default gen_random_uuid(), owner_id uuid not null references auth.users(id) on delete cascade,
 rows jsonb not null, errors jsonb not null default '[]', published boolean not null default false,
 expires_at timestamptz not null default now()+interval '24 hours'
);
alter table public.vci_schedule_imports enable row level security;
revoke all on public.vci_schedule_imports from anon,authenticated;
create unique index vci_username_unique on public.vci_accounts(lower(username));
create index vci_accounts_class on public.vci_accounts(class_id);
create table public.vci_student_details (
 account_id bigint primary key references public.vci_accounts(id) on delete cascade,
 surname text not null default '' check(length(surname)<=150), given_name text not null default '' check(length(given_name)<=150),
 birth_date text not null default '' check(birth_date='' or (birth_date ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' and birth_date::date<=current_date)),
 birth_place text not null default '' check(length(birth_place)<=150), gender text not null default '' check(length(gender)<=30), ethnicity text not null default '' check(length(ethnicity)<=100),
 national_id text not null default '' check(national_id='' or national_id ~ '^[0-9]{12}$'), note text not null default '' check(length(note)<=1000)
);
create unique index vci_national_id_unique on public.vci_student_details(national_id) where national_id<>'';
create table public.vci_timetable_links (
 id bigint generated by default as identity primary key,
 class_id bigint not null references public.vci_classes(id) on delete cascade,
 academic_year text not null check(academic_year ~ '^[0-9]{4}-[0-9]{4}$' and split_part(academic_year,'-',1)::int between 1900 and 2199 and split_part(academic_year,'-',2)::int=split_part(academic_year,'-',1)::int+1),
 semester text not null check(semester in ('1','2','summer')), kind text not null check(kind in ('hoc','thi')),
 title text not null check(length(trim(title)) between 1 and 200),
 url text not null check(length(url)<=3000 and url ~ '^https://(drive[.]google[.]com|docs[.]google[.]com)(:443)?/[^[:space:]]+$'),
 note text not null default '' check(length(note)<=1000), active boolean not null default true,
 version integer not null default 1, updated_at timestamptz not null default now(),
 unique(class_id,academic_year,semester,kind)
);
create index vci_links_class on public.vci_timetable_links(class_id,academic_year);
create table public.vci_schedules (
 id bigint generated by default as identity primary key,
 class_id bigint not null references public.vci_classes(id) on delete cascade,
 date date not null, start time not null, "end" time not null check("end">start),
 subject text not null check(length(trim(subject)) between 1 and 200),
 lecturer text not null check(length(trim(lecturer)) between 1 and 150), room text not null check(length(trim(room)) between 1 and 100),
 kind text not null check(kind in ('hoc','thi')), status text not null check(status in ('hoc','nghi','hoc_bu')),
 note text not null default '' check(length(note)<=1000), updated_at timestamptz not null default now(),
 unique(class_id,date,start,kind)
);
create index vci_schedules_class_date on public.vci_schedules(class_id,date);
create table public.vci_notices (
 id bigint generated by default as identity primary key,
 class_id bigint references public.vci_classes(id) on delete cascade,
 title text not null check(length(trim(title)) between 1 and 200),
 body text not null check(length(trim(body)) between 1 and 5000), created_at timestamptz not null default now()
);
create index vci_notices_class on public.vci_notices(class_id,created_at desc);
create table public.vci_audit (
 id bigint generated by default as identity primary key, actor text not null, action text not null,
 detail text not null, created_at timestamptz not null default now()
);

create function vci_private.account() returns public.vci_accounts
language plpgsql stable security definer set search_path='' as $$
declare a public.vci_accounts;
begin
 select * into a from public.vci_accounts where auth_id=auth.uid();
 if a.id is null then raise exception 'Vui lòng đăng nhập bằng tài khoản do trường cấp' using errcode='28000'; end if;
 -- Reject revoked sessions even when an old access JWT has not expired yet.
 if not exists(select 1 from auth.sessions where id=(auth.jwt()->>'session_id')::uuid and user_id=a.auth_id
   and (a.credentials_since is null or created_at>=a.credentials_since)) then
   raise exception 'Phiên đăng nhập đã kết thúc. Vui lòng đăng nhập lại.' using errcode='28000';
 end if;
 return a;
end $$;
create function public.vci_is_admin() returns boolean
language sql stable security definer set search_path='' as $$ select (vci_private.account()).role='admin' $$;
create function public.vci_class_id() returns bigint
language sql stable security definer set search_path='' as $$ select (vci_private.account()).class_id $$;
revoke all on function public.vci_is_admin(),public.vci_class_id() from public,anon;
grant execute on function public.vci_is_admin(),public.vci_class_id() to authenticated;

alter table public.vci_classes enable row level security;
alter table public.vci_accounts enable row level security;
alter table public.vci_student_details enable row level security;
alter table public.vci_student_imports enable row level security;
alter table public.vci_timetable_links enable row level security;
alter table public.vci_schedules enable row level security;
alter table public.vci_notices enable row level security;
alter table public.vci_audit enable row level security;
create policy classes_read on public.vci_classes for select to authenticated using ((select public.vci_is_admin()) or id=(select public.vci_class_id()));
create policy accounts_read on public.vci_accounts for select to authenticated using ((select public.vci_is_admin()) or auth_id=(select auth.uid()));
create policy details_read on public.vci_student_details for select to authenticated using ((select public.vci_is_admin()));
create policy imports_read on public.vci_student_imports for select to authenticated using ((select public.vci_is_admin()) and owner_id=(select auth.uid()) and expires_at>now());
create policy links_read on public.vci_timetable_links for select to authenticated using ((select public.vci_is_admin()) or (class_id=(select public.vci_class_id()) and active));
create policy schedules_read on public.vci_schedules for select to authenticated using ((select public.vci_is_admin()) or class_id=(select public.vci_class_id()));
create policy notices_read on public.vci_notices for select to authenticated using ((select public.vci_is_admin()) or class_id is null or class_id=(select public.vci_class_id()));
create policy audit_read on public.vci_audit for select to authenticated using ((select public.vci_is_admin()));
-- No direct writes: protected RPCs enforce validation, revisions and audit records.
revoke all on public.vci_classes,public.vci_accounts,public.vci_student_details,public.vci_student_imports,public.vci_timetable_links,public.vci_schedules,public.vci_notices,public.vci_audit from anon,authenticated;
grant select on public.vci_classes,public.vci_accounts,public.vci_student_details,public.vci_student_imports,public.vci_timetable_links,public.vci_schedules,public.vci_notices,public.vci_audit to authenticated;
grant all on public.vci_classes,public.vci_accounts,public.vci_student_details,public.vci_student_imports,public.vci_timetable_links,public.vci_schedules,public.vci_notices,public.vci_audit to service_role;
grant usage,select on all sequences in schema public to service_role;

-- Only trusted Auth admin API app_metadata can provision accounts. user_metadata
-- and public signup cannot grant membership, class access or administrator rights.
create function vci_private.provision_account() returns trigger
language plpgsql security definer set search_path='' as $$
declare m jsonb:=new.raw_app_meta_data->'vci'; a bigint; c public.vci_classes; b public.vci_student_imports;
begin
 if m is null then return new; end if;
 perform pg_advisory_xact_lock(846311);
 if m->>'role'='student' then
   select * into c from public.vci_classes where id=(m->>'class_id')::bigint for update;
   if c.id is null then raise exception 'Lớp nhận sinh viên không tồn tại'; end if;
 end if;
 if m->>'import_id' is not null then
   select * into b from public.vci_student_imports where id=(m->>'import_id')::uuid for update;
   if b.id is null or b.finished or b.expires_at<=now() then raise exception 'Bản nháp đã hết hạn'; end if;
   if (b.rows->((m->>'import_index')::integer)->>'username') is distinct from (m->>'username') then raise exception 'Dòng nhập không khớp'; end if;
 end if;
 insert into public.vci_accounts(auth_id,username,full_name,role,class_id,import_id,import_index)
 values(new.id,m->>'username',m->>'full_name',m->>'role',(m->>'class_id')::bigint,(m->>'import_id')::uuid,(m->>'import_index')::int) returning id into a;
 if m->>'role'='student' then
 insert into public.vci_student_details(account_id,surname,given_name,birth_date,birth_place,gender,ethnicity,national_id,note)
 values(a,coalesce(m->>'surname',''),coalesce(m->>'given_name',''),coalesce(m->>'birth_date',''),coalesce(m->>'birth_place',''),coalesce(m->>'gender',''),coalesce(m->>'ethnicity',''),coalesce(m->>'national_id',''),coalesce(m->>'note',''));
 end if;
 return new;
end $$;
create trigger vci_auth_created after insert on auth.users for each row execute function vci_private.provision_account();

create function vci_private.password_changed() returns trigger
language plpgsql security definer set search_path='' as $$
begin
 if old.encrypted_password is distinct from new.encrypted_password then
  update public.vci_accounts set credentials_since=clock_timestamp() where auth_id=new.id;
  insert into public.vci_audit(actor,action,detail) select username,'password','Mật khẩu thay đổi; các phiên cũ không còn quyền truy cập dữ liệu' from public.vci_accounts where auth_id=new.id;
 end if;
 return new;
end $$;
create trigger vci_auth_password_changed after update of encrypted_password on auth.users for each row execute function vci_private.password_changed();
revoke all on function vci_private.password_changed() from public,anon,authenticated;

